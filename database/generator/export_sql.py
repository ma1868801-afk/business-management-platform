"""Write the dataset as PostgreSQL COPY scripts (text format) from the DataFrames of build_dataset.build_all().

    python3 export_sql.py [seed]

Output (database/sql/):  02_data_1_reference.sql, 02_data_2_sales_orders.sql, 02_data_3_sales_order_items.sql,
                         02_data_4_returns_inventory_purchasing.sql
Output (database/output/): bmp_dataset_all.sql.gz  (schema + data + indexes in one file; roles and verification stay separate)
"""
import gzip
import re
import sys
import time
import pathlib
import numpy as np
import pandas as pd
import build_dataset as B

ROOT = B.ROOT
SQLDIR = ROOT / "database" / "sql"
OUTDIR = ROOT / "database" / "output"

PARTS = {
    "02_data_1_reference.sql": ["branches", "product_categories", "suppliers", "products", "customers", "promotions", "calendar",
                                "monthly_sales_targets"],
    "02_data_2_sales_orders.sql": ["sales_orders"],
    "02_data_3_sales_order_items.sql": ["sales_order_items"],
    "02_data_4_returns_inventory_purchasing.sql": ["sales_returns", "inventory_levels", "inventory_snapshots", "purchase_orders",
                                                  "purchase_order_items", "stock_adjustments"],
}


def column_types():
    """{table: {column: sql type}} from the CREATE TABLE statements."""
    txt = B.SCHEMA.read_text()
    out = {}
    for m in re.finditer(r"CREATE TABLE (\w+) \((.*?)\n\);", txt, re.S):
        cols = {}
        for line in m.group(2).split("\n"):
            line = line.strip().rstrip(",")
            if not line or line.startswith("CONSTRAINT") or "GENERATED ALWAYS" in line:
                continue
            name, typ = line.split()[0], line.split()[1]
            cols[name] = typ.upper()
        out[m.group(1)] = cols
    return out


def fmt_col(s, typ):
    """Format one column as COPY text (strings, NULL as \\N)."""
    null = s.isna()
    if typ.startswith(("INTEGER", "BIGINT", "SMALLINT")):
        out = pd.Series(pd.array(s, dtype="Int64").astype(str), index=s.index).where(~null, r"\N")
    elif typ.startswith("NUMERIC"):
        scale = int(re.search(r",(\d+)\)", typ).group(1))
        out = pd.Series(np.char.mod(f"%.{scale}f", pd.to_numeric(s, errors="coerce").to_numpy(dtype=float)), index=s.index).where(~null, r"\N")
    elif typ == "BOOLEAN":
        out = s.map({True: "t", False: "f"}).where(~null, r"\N")
    elif typ == "DATE":
        out = pd.to_datetime(s).dt.strftime("%Y-%m-%d").where(~null, r"\N")
    elif typ == "TIMESTAMP":
        out = pd.to_datetime(s).dt.strftime("%Y-%m-%d %H:%M:%S").where(~null, r"\N")
    else:
        out = s.astype(str).where(~null, r"\N")
        bad = out.str.contains(r"[\t\n\r\\]", regex=True) & ~null
        assert not bad.any(), "special character in text column"
    return out


def table_text(name, df, types):
    cols = []
    for c in df.columns:
        cols.append(fmt_col(df[c], types[name][c]).rename(c))
    tx = pd.concat(cols, axis=1)
    body = tx.to_csv(sep="\t", header=False, index=False, quoting=3, lineterminator="\n")   # 3 = QUOTE_NONE
    head = f"COPY {name} ({', '.join(df.columns)}) FROM stdin;\n"
    return head + body + "\\.\n\n"


def main(seed):
    t0 = time.time()
    D = B.build_all(seed)
    types = column_types()
    SQLDIR.mkdir(exist_ok=True)
    OUTDIR.mkdir(exist_ok=True)
    stats = {}
    for fn, tabs in PARTS.items():
        path = SQLDIR / fn
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(f"-- Business Management Platform, Phase 2 dataset part {fn[8]}: {', '.join(tabs)}.\n")
            f.write(f"-- Generated by database/generator/export_sql.py with seed {seed}. Load after 01_schema.sql, inside one transaction per part.\n")
            f.write("BEGIN;\nSET LOCAL synchronous_commit = off;\n\n")
            for t in tabs:
                f.write(f"-- {t}: {len(D[t]):,d} rows\n")
                f.write(table_text(t, D[t], types))
                stats[t] = len(D[t])
            if fn.startswith("02_data_4"):
                f.write("COMMIT;\nANALYZE;\n")
            else:
                f.write("COMMIT;\n")
        print(fn, round(path.stat().st_size / 1e6, 1), "MB")
    # combined compressed copy: schema, data, indexes
    gz = OUTDIR / "bmp_dataset_all.sql.gz"
    with gzip.open(gz, "wb", compresslevel=9) as z:
        z.write(f"-- Business Management Platform: complete dataset (schema + data + indexes), seed {seed}.\n".encode())
        z.write(b"-- Usage: createdb bmp && gunzip -c bmp_dataset_all.sql.gz | psql -v ON_ERROR_STOP=1 bmp\n\n")
        for fn in ["01_schema.sql"] + list(PARTS) + ["03_indexes.sql"]:
            z.write(f"\n-- ===== {fn} =====\n".encode())
            z.write((SQLDIR / fn).read_bytes())
    total = sum((SQLDIR / fn).stat().st_size for fn in PARTS)
    print("total data MB", round(total / 1e6, 1), "gz MB", round(gz.stat().st_size / 1e6, 1), "seconds", round(time.time() - t0, 1))
    return stats


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else B.DEFAULT_SEED)
