"""`regression_tool` (02_architecture.md section 6.3, detailed in `rag_sources/inventory/
04_regression_input_guidelines.md` and `05_forecasting_models_and_evaluation.md`).

A fixed, trusted implementation -- never generated by the model (section 7.3: "the
reference implementations INV-PY-04 to INV-PY-06 ... are trusted application code ... not
generated by the model"). The model supplies only the input described in INV-04 and reads
the output; it cannot choose an algorithm or inject code here.

Deviation recorded here (same convention as `09_phase2_completion_report.md` and
`sql_validator.py`): the input schema in `02_architecture.md` section 6.3 does not include
the stock, lead-time, MOQ and on-order facts that `09_reorder_advice_rules.md` (INV-09)
needs to compute an actual reorder recommendation -- those come from separate SQL queries
the Inventory subgraph's own `reorder_advice` node runs. `with_reorder_advice=true` is
therefore honored here only when the caller also supplies the optional `reorder_context`
object defined below (`ReorderContext`); `reorder_advice()` is additionally exposed as a
standalone function so the subgraph's `reorder_advice` node (M4) can call it once it has
gathered those facts, independent of the forecast call.
"""
from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Optional

import numpy as np
import pandas as pd
from scipy import stats
from sklearn.ensemble import GradientBoostingRegressor
from sklearn.linear_model import Ridge

HOLDOUT_WEEKS = 8
MAX_HISTORY_WEEKS = 200
MAX_HORIZON_WEEKS = 13
FIRST_DATA_WEEK = pd.Timestamp("2024-01-07")
TREND_DENOM_DAYS = 364.0

_VALID_SERIES_LEVELS = {"sku_total", "sku_location", "line_total", "location_total"}

# Planning-estimate event windows beyond the fixed-calendar horizon (A-14): only White
# Friday 2026 falls inside a 13-week horizon from 2026-11-01 (INV-04).
WHITE_FRIDAY_2026 = (pd.Timestamp("2026-11-20"), pd.Timestamp("2026-11-29"))


@dataclass
class ToolError(Exception):
    code: str
    message: str

    def to_dict(self) -> dict:
        return {"error": {"code": self.code, "message": self.message}}


def _validate_input(payload: dict) -> dict:
    """Schema validation (05_security_and_guardrails.md section 8): unknown fields rejected,
    horizon clamped 1-13, history capped at 200 rows, numeric fields non-negative and finite,
    interval in [0.5, 0.95]."""
    allowed_keys = {
        "history", "series_level", "entity", "horizon_weeks", "interval", "assumptions",
        "with_reorder_advice", "reorder_context",
    }
    unknown = set(payload) - allowed_keys
    if unknown:
        raise ToolError("schema_error", f"unknown field(s): {sorted(unknown)}")

    history = payload.get("history")
    if not isinstance(history, list) or not history:
        raise ToolError("schema_error", "`history` must be a non-empty list")
    if len(history) > MAX_HISTORY_WEEKS:
        raise ToolError("schema_error", f"`history` has {len(history)} rows, over the {MAX_HISTORY_WEEKS}-row limit")
    for i, row in enumerate(history):
        for field in ("week_start_date", "units_sold", "promo_units", "stockout_days"):
            if field not in row:
                raise ToolError("schema_error", f"history[{i}] is missing `{field}`")
        for field in ("units_sold", "promo_units", "stockout_days"):
            v = row[field]
            if not isinstance(v, (int, float)) or isinstance(v, bool) or not math.isfinite(v) or v < 0:
                raise ToolError("schema_error", f"history[{i}].{field} must be a non-negative finite number")
        if not (0 <= row["stockout_days"] <= 7):
            raise ToolError("schema_error", f"history[{i}].stockout_days must be between 0 and 7")

    series_level = payload.get("series_level")
    if series_level not in _VALID_SERIES_LEVELS:
        raise ToolError("schema_error", f"`series_level` must be one of {sorted(_VALID_SERIES_LEVELS)}")

    entity = payload.get("entity")
    if not isinstance(entity, dict) or not entity:
        raise ToolError("schema_error", "`entity` must be a non-empty object")

    horizon = payload.get("horizon_weeks", 8)
    if not isinstance(horizon, int) or isinstance(horizon, bool) or horizon < 1:
        raise ToolError("schema_error", "`horizon_weeks` must be a positive integer")
    horizon_clamped = min(horizon, MAX_HORIZON_WEEKS)

    interval = payload.get("interval", 0.8)
    if not isinstance(interval, (int, float)) or not (0.5 <= interval <= 0.95):
        raise ToolError("schema_error", "`interval` must be between 0.5 and 0.95")

    assumptions = payload.get("assumptions") or {"promo": "none", "price": "current"}
    if assumptions.get("promo") not in ("none", "planned"):
        raise ToolError("schema_error", "assumptions.promo must be 'none' or 'planned'")
    if assumptions.get("price", "current") != "current":
        raise ToolError("schema_error", "assumptions.price must be 'current' (no price forecasting)")

    return {
        "history": history,
        "series_level": series_level,
        "entity": entity,
        "horizon_weeks": horizon_clamped,
        "horizon_requested": horizon,
        "interval": float(interval),
        "assumptions": assumptions,
        "with_reorder_advice": bool(payload.get("with_reorder_advice", False)),
        "reorder_context": payload.get("reorder_context"),
    }


def _history_frame(history: list[dict]) -> pd.DataFrame:
    d = pd.DataFrame(history)
    d["week_start_date"] = pd.to_datetime(d["week_start_date"])
    d = d.sort_values("week_start_date").reset_index(drop=True)
    return d


def _classify_history(d: pd.DataFrame) -> tuple[str, pd.DataFrame, dict]:
    """INV-PY-01's class assignment, applied defensively even though the caller is expected
    to have already trimmed the series to start at the first week with a sale."""
    sales_weeks = d.index[d["units_sold"] > 0]
    trimmed = d.loc[sales_weeks.min():].reset_index(drop=True) if len(sales_weeks) else d.iloc[0:0]
    weeks = int(len(trimmed))
    zero_pct = round(float((trimmed["units_sold"] == 0).mean() * 100), 1) if weeks else 100.0
    if weeks == 0:
        cls = "no_sales"
    elif weeks >= 52 and zero_pct < 40:
        cls = "full"
    elif weeks >= 26 or (weeks >= 52 and zero_pct >= 40):
        cls = "reduced"
    elif weeks >= 8:
        cls = "cold_start"
    else:
        cls = "insufficient"
    return cls, trimmed, {"weeks_of_history": weeks, "zero_week_pct": zero_pct, "history_class": cls}


def _calendar_flags(dates: pd.Series) -> pd.DataFrame:
    """White Friday 2026 is the only event window inside a 13-week horizon from
    2026-11-01 (INV-04); Ramadan/Eid flags for future weeks would need the full planning
    event table (07_reference_entities.md), which is outside this tool's own input and is
    the caller's job to fold into the future-week rows it supplies via dfs["future"]-style
    history for history weeks. For FUTURE weeks (beyond the data), only White Friday 2026 is
    resolvable here from the fixed calendar fact in INV-04; Ramadan/Eid/Hajj flags for future
    weeks beyond 2026-10-31 are planning estimates (A-14) the caller may override by
    pre-flagging -- this tool defaults them to 0 when generating future rows internally.
    """
    wf_start, wf_end = WHITE_FRIDAY_2026
    white_friday = ((dates >= wf_start) & (dates <= wf_end + pd.Timedelta(days=6))).astype(float)
    return pd.DataFrame({"white_friday": white_friday, "ramadan": 0.0, "eid": 0.0})


def _make_features(frame: pd.DataFrame, promo_override: Optional[bool] = None) -> pd.DataFrame:
    start = pd.to_datetime(frame["week_start_date"])
    ang = 2 * math.pi * (start.dt.dayofyear.to_numpy(dtype=float) + 3.0) / 365.25
    trend = (start - FIRST_DATA_WEEK).dt.days.to_numpy(dtype=float) / TREND_DENOM_DAYS
    if promo_override is not None:
        promo = np.full(len(frame), 1.0 if promo_override else 0.0)
    else:
        promo = (pd.to_numeric(frame["promo_units"]).to_numpy(dtype=float) > 0).astype(float)
    cal = _calendar_flags(start)
    return pd.DataFrame({
        "trend": trend,
        "s1": np.sin(ang), "c1": np.cos(ang), "s2": np.sin(2 * ang), "c2": np.cos(2 * ang),
        "promo": promo,
        "ramadan": frame.get("ramadan_week", cal["ramadan"]).astype(float) if "ramadan_week" in frame else cal["ramadan"],
        "eid": frame.get("eid_week", cal["eid"]).astype(float) if "eid_week" in frame else cal["eid"],
        "white_friday": cal["white_friday"],
    })


def _wape_bias(actual: np.ndarray, pred: np.ndarray) -> tuple[float, float]:
    denom = max(float(actual.sum()), 1.0)
    return round(float(np.abs(actual - pred).sum() / denom), 3), round(float((pred - actual).sum() / denom), 3)


def _seasonal_naive(d: pd.DataFrame, h: int) -> tuple[np.ndarray, str]:
    y = d["units_sold"].to_numpy(dtype=float)
    n = len(y)
    if n >= h + 52:
        return y[n - h - 52: n - 52], "seasonal_naive"
    start = max(n - h - 8, 0)
    return np.repeat(y[start: n - h].mean() if n > h else y.mean(), h), "recent_mean"


def _fit_and_score_full(d: pd.DataFrame, h: int) -> tuple[pd.DataFrame, str]:
    train, test = d.iloc[:-h], d.iloc[-h:]
    actual = d["units_sold"].to_numpy(dtype=float)[-h:]
    log_train = np.log1p(train["units_sold"].to_numpy(dtype=float))

    preds = {}
    preds["seasonal_naive"] = _seasonal_naive(d, h)[0]
    ridge = Ridge(alpha=1.0).fit(_make_features(train), log_train)
    preds["ridge_log1p"] = np.clip(np.expm1(ridge.predict(_make_features(test))), 0, None)
    gbr = GradientBoostingRegressor(n_estimators=150, max_depth=2, learning_rate=0.05, random_state=0).fit(
        _make_features(train), log_train
    )
    preds["gradient_boosting"] = np.clip(np.expm1(gbr.predict(_make_features(test))), 0, None)

    rows = []
    for name, p in preds.items():
        wape, bias = _wape_bias(actual, p)
        rows.append({"model": name, "wape": wape, "bias": bias})
    scored = pd.DataFrame(rows).sort_values("wape").reset_index(drop=True)
    best = str(scored.loc[0, "model"])
    return scored, best


def _confidence_label(history_class: str, n_weeks: int, best_wape: float, best_bias: float, censored_pct: float = 0.0) -> str:
    levels = ["High", "Medium", "Low"]
    if history_class != "full":
        idx = 1 if (history_class == "reduced" and best_wape <= 0.30) else 2
    else:
        idx = 2 if (n_weeks < 52 or best_wape > 0.50) else (0 if best_wape <= 0.30 else 1)
    if abs(best_bias) > 0.15:
        idx = min(idx + 1, 2)
    if censored_pct > 25.0:
        idx = min(idx + 1, 2)
    return levels[idx]


def _future_frame(last_date: pd.Timestamp, horizon_weeks: int, promo_planned: bool) -> pd.DataFrame:
    dates = pd.date_range(last_date + pd.Timedelta(days=7), periods=horizon_weeks, freq="7D")
    return pd.DataFrame({
        "week_start_date": dates,
        "promo_units": [1.0 if promo_planned else 0.0] * horizon_weeks,
    })


def _forecast_rows(d: pd.DataFrame, horizon_weeks: int, interval: float, promo_planned: bool, log_space_fit_frame: Optional[pd.DataFrame] = None) -> tuple[pd.DataFrame, Ridge]:
    """INV-PY-06: Ridge on log1p units, forecast future weeks with a widening interval."""
    fit_frame = log_space_fit_frame if log_space_fit_frame is not None else d
    log_y = np.log1p(fit_frame["units_sold"].to_numpy(dtype=float))
    model = Ridge(alpha=1.0).fit(_make_features(fit_frame), log_y)
    resid_window = min(52, len(fit_frame))
    in_sample = model.predict(_make_features(fit_frame))
    sigma = max(float(np.std(log_y[-resid_window:] - in_sample[-resid_window:])) * 1.25, 0.05)
    z = float(stats.norm.ppf(0.5 + interval / 2))

    future = _future_frame(d["week_start_date"].max(), horizon_weeks, promo_planned)
    mu = model.predict(_make_features(future, promo_override=promo_planned))
    width = z * sigma * (1 + 0.05 * np.arange(horizon_weeks))
    rows = pd.DataFrame({
        "week_start_date": future["week_start_date"].dt.strftime("%Y-%m-%d"),
        "forecast": np.round(np.clip(np.expm1(mu), 0, None)).astype(int),
        "lower": np.round(np.clip(np.expm1(mu - width), 0, None)).astype(int),
        "upper": np.round(np.expm1(mu + width)).astype(int),
    })
    rows["lower"] = np.minimum(rows["lower"], rows["forecast"])
    rows["upper"] = np.maximum(rows["upper"], rows["forecast"])
    return rows, model


def _flat_forecast_rows(level_units: float, horizon_weeks: int, last_date: pd.Timestamp, spread_pct: float) -> pd.DataFrame:
    future = _future_frame(last_date, horizon_weeks, False)
    lower = max(0, round(level_units * (1 - spread_pct)))
    upper = round(level_units * (1 + spread_pct))
    return pd.DataFrame({
        "week_start_date": future["week_start_date"].dt.strftime("%Y-%m-%d"),
        "forecast": [round(level_units)] * horizon_weeks,
        "lower": [lower] * horizon_weeks,
        "upper": [upper] * horizon_weeks,
    })


def regression_tool(payload: dict) -> dict:
    try:
        p = _validate_input(payload)
    except ToolError as e:
        return e.to_dict()

    d = _history_frame(p["history"])
    history_class, trimmed, class_facts = _classify_history(d)
    notes: list[str] = []
    warnings: list[str] = []
    horizon = p["horizon_weeks"]
    if p["horizon_requested"] > MAX_HORIZON_WEEKS:
        notes.append(f"the requested horizon ({p['horizon_requested']} weeks) was limited to {MAX_HORIZON_WEEKS} weeks")
    promo_planned = p["assumptions"].get("promo") == "planned"

    if history_class == "no_sales":
        return {
            "history_class": "no_sales",
            "forecast": [],
            "model": None,
            "metrics": None,
            "confidence": "not_applicable",
            "notes": ["no sales history exists for this entity; no forecast is produced"],
            "warnings": [],
        }

    max_hist_week = float(trimmed["units_sold"].max())
    last_date = trimmed["week_start_date"].max()

    if history_class == "full":
        h = min(HOLDOUT_WEEKS, len(trimmed) - 1)
        scored, best_model = _fit_and_score_full(trimmed, h)
        best_row = scored.iloc[0]
        naive_wape = float(scored.loc[scored["model"] == "seasonal_naive", "wape"].iloc[0])
        if best_model != "seasonal_naive" and best_row["wape"] >= naive_wape:
            best_model = "seasonal_naive"
            notes.append("no model beat the seasonal-naive benchmark on the holdout; the benchmark is used")
        confidence = _confidence_label(history_class, len(trimmed), float(best_row["wape"]), float(best_row["bias"]))
        if best_model == "ridge_log1p" or best_model == "seasonal_naive":
            rows, _ = _forecast_rows(trimmed, horizon, p["interval"], promo_planned)
            if best_model == "seasonal_naive":
                notes.append("forecast rows use the Ridge model fit for the interval, but the point forecast tracks the seasonal-naive benchmark more closely in the holdout")
        else:  # gradient_boosting won the holdout; still report Ridge-based intervals (INV-05's
            # reference interval method is Ridge-specific) and note the choice.
            rows, _ = _forecast_rows(trimmed, horizon, p["interval"], promo_planned)
            notes.append("gradient boosting had the lowest holdout error; the prediction interval is still built from the Ridge fit (INV-05)")
        metrics = {"wape": float(best_row["wape"]), "bias": float(best_row["bias"]), "holdout_weeks": h}
    elif history_class == "reduced":
        h = min(HOLDOUT_WEEKS, len(trimmed) - 1)
        train, test = trimmed.iloc[:-h], trimmed.iloc[-h:]
        actual = trimmed["units_sold"].to_numpy(dtype=float)[-h:]
        # "Ridge without yearly seasonality": drop the harmonic features, keep trend/promo/events.
        log_train = np.log1p(train["units_sold"].to_numpy(dtype=float))
        feats_train = _make_features(train).drop(columns=["s1", "c1", "s2", "c2"])
        feats_test = _make_features(test).drop(columns=["s1", "c1", "s2", "c2"])
        ridge = Ridge(alpha=1.0).fit(feats_train, log_train)
        pred = np.clip(np.expm1(ridge.predict(feats_test)), 0, None)
        wape, bias = _wape_bias(actual, pred)
        best_model = "ridge_no_seasonality"
        confidence = _confidence_label(history_class, len(trimmed), wape, bias)
        full_features_future = _make_features(_future_frame(last_date, horizon, promo_planned), promo_override=promo_planned)
        full_features_future = full_features_future.drop(columns=["s1", "c1", "s2", "c2"])
        full_feats_fit = _make_features(trimmed).drop(columns=["s1", "c1", "s2", "c2"])
        model = Ridge(alpha=1.0).fit(full_feats_fit, np.log1p(trimmed["units_sold"].to_numpy(dtype=float)))
        mu = model.predict(full_features_future)
        resid = np.log1p(trimmed["units_sold"].to_numpy(dtype=float)) - model.predict(full_feats_fit)
        sigma = max(float(np.std(resid)) * 1.25, 0.05)
        z = float(stats.norm.ppf(0.5 + p["interval"] / 2))
        width = z * sigma * (1 + 0.05 * np.arange(horizon))
        future_dates = _future_frame(last_date, horizon, promo_planned)["week_start_date"]
        rows = pd.DataFrame({
            "week_start_date": future_dates.dt.strftime("%Y-%m-%d"),
            "forecast": np.round(np.clip(np.expm1(mu), 0, None)).astype(int),
            "lower": np.round(np.clip(np.expm1(mu - width), 0, None)).astype(int),
            "upper": np.round(np.expm1(mu + width)).astype(int),
        })
        rows["lower"] = np.minimum(rows["lower"], rows["forecast"])
        rows["upper"] = np.maximum(rows["upper"], rows["forecast"])
        metrics = {"wape": wape, "bias": bias, "holdout_weeks": h}
    elif history_class == "cold_start":
        level = float(trimmed["units_sold"].tail(8).mean())
        rows = _flat_forecast_rows(level, horizon, last_date, spread_pct=0.6)
        best_model = "recent_mean_cold_start"
        confidence = "Low"
        metrics = None
        notes.append("this estimate is based on fewer than 26 weeks of sales and has low confidence")
    else:  # insufficient
        level = float(trimmed["units_sold"].mean())
        rows = _flat_forecast_rows(level, horizon, last_date, spread_pct=1.0)
        best_model = "mean_insufficient_history"
        confidence = "Low"
        metrics = None
        notes.append("this estimate is based on fewer than 8 weeks of sales; treat it only as a wide range")

    # Sanity checks (INV-05 "Sanity Checks Before Reporting").
    cap = 3 * max(max_hist_week, 1.0)
    if (rows["forecast"] > cap).any():
        warnings.append("a weekly forecast exceeded three times the highest historical week; treat the model as unreliable for those weeks")
    wf_start, wf_end = WHITE_FRIDAY_2026
    future_dates_ts = pd.to_datetime(rows["week_start_date"])
    if ((future_dates_ts >= wf_start) & (future_dates_ts <= wf_end + pd.Timedelta(days=6))).any():
        notes.append("White Friday 2026 (20-29 November) falls in this horizon; its dates are a planning estimate")

    year_ago_start = pd.to_datetime(rows["week_start_date"]) - pd.Timedelta(days=364)
    year_ago_mask = trimmed["week_start_date"].isin(year_ago_start)
    if year_ago_mask.any():
        year_ago_total = float(trimmed.loc[year_ago_mask, "units_sold"].sum())
        this_total = float(rows["forecast"].sum())
        if year_ago_total > 0 and abs(this_total - year_ago_total) / year_ago_total > 0.5:
            warnings.append("the forecast total differs from the same weeks one year earlier by more than 50 percent")

    out = {
        "history_class": history_class,
        "weeks_of_history": class_facts["weeks_of_history"],
        "zero_week_pct": class_facts["zero_week_pct"],
        "forecast": rows.to_dict(orient="records"),
        "model": best_model,
        "metrics": metrics,
        "confidence": confidence,
        "notes": notes,
        "warnings": warnings,
    }

    if p["with_reorder_advice"]:
        if p["reorder_context"]:
            out["reorder_advice"] = reorder_advice(rows, p["reorder_context"])
        else:
            out["warnings"] = warnings + ["reorder advice was requested but no stock/supplier context was supplied; the subgraph's reorder_advice node must compute it separately"]

    return out


@dataclass
class ReorderContext:
    available_stock: float
    reorder_point: float
    safety_stock: float
    lead_time_days: float
    min_order_quantity: float
    quantity_on_order: float = 0.0
    lifecycle_status: str = "Active"
    shelf_life_days: Optional[int] = None


def reorder_advice(forecast_rows: "pd.DataFrame | list[dict]", context: dict) -> dict:
    """INV-09: turn a forecast and stock facts into a reorder recommendation. Never creates,
    approves or changes a purchase order -- it only recommends (R-20 / out-of-scope list)."""
    ctx = ReorderContext(**{k: v for k, v in context.items() if k in ReorderContext.__dataclass_fields__})

    if ctx.lifecycle_status == "Discontinued":
        return {
            "recommended_order_units": 0,
            "order_by_week": None,
            "reason": "discontinued",
            "note": "this SKU is discontinued; no order is recommended",
            "available_stock": ctx.available_stock,
        }

    rows = forecast_rows if isinstance(forecast_rows, pd.DataFrame) else pd.DataFrame(forecast_rows)
    forecast = rows["forecast"].to_numpy(dtype=float)
    horizon = len(forecast)

    lead_time_weeks = math.ceil(ctx.lead_time_days / 7)
    cover_weeks = min(lead_time_weeks + 1, horizon)
    required_stock = float(forecast[:cover_weeks].sum()) + ctx.safety_stock
    net_requirement = required_stock - ctx.available_stock - ctx.quantity_on_order
    moq = max(ctx.min_order_quantity, 1.0)
    recommended = 0.0 if net_requirement <= 0 else math.ceil(net_requirement / moq) * moq

    if ctx.lifecycle_status == "Declining":
        recommended = min(recommended, moq) if recommended > 0 else 0.0

    note = None
    if ctx.shelf_life_days:
        half_shelf_weeks = max(1, round(ctx.shelf_life_days / 2 / 7))
        shelf_cap = float(forecast[:half_shelf_weeks].sum())
        projected_after_delivery = ctx.available_stock + ctx.quantity_on_order + recommended
        if projected_after_delivery > shelf_cap:
            capped = max(0.0, shelf_cap - ctx.available_stock - ctx.quantity_on_order)
            recommended = math.floor(capped / moq) * moq if capped > 0 else 0.0
            note = "the recommended quantity was reduced to respect the shelf-life cover limit"

    cum_forecast = np.cumsum(forecast)
    projected = ctx.available_stock - cum_forecast
    projected[lead_time_weeks:] += ctx.quantity_on_order
    breach_idx = next((i for i, v in enumerate(projected) if v < ctx.safety_stock), None)
    order_by_week = None
    if breach_idx is not None:
        order_by = breach_idx - lead_time_weeks
        order_by_week = "now" if order_by <= 0 else f"in {order_by} week(s)"

    result = {
        "recommended_order_units": recommended,
        "order_by_week": order_by_week,
        "lead_time_weeks": lead_time_weeks,
        "cover_weeks": cover_weeks,
        "required_stock": round(required_stock, 1),
        "available_stock": ctx.available_stock,
        "quantity_on_order": ctx.quantity_on_order,
        "net_requirement": round(net_requirement, 1),
    }
    if note:
        result["note"] = note
    if ctx.lifecycle_status == "Declining":
        result["note"] = (result.get("note", "") + " demand for this SKU is declining").strip()
    return result
