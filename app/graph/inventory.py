"""Inventory subgraph (02_architecture.md section 4.2):
rag_retrieve -> plan (stock status or forecast) -> generate_sql -> sql_validator ->
postgres_tool -> (bypass if no forecast requested) -> format_node_response
  -> (else) prepare_weekly_history -> regression_tool -> reorder_advice -> format_node_response

The stock-status path (current quantities, status lists, supplier facts, historical sales)
is free-text-to-SQL, so it is dependency-injected exactly like `data_analysis.py`'s
`sql_generator` -- the LLM's job in production, stubbed in tests.

The forecast path is different: `prepare_weekly_history`'s two SQL extractions (the weekly
demand series and the weighted stockout days) are a small, fixed family of patterns per
entity (INV-SQL-14/15/16; `04_regression_input_guidelines.md`'s own Data Preparation Steps),
not open-ended natural language, so they are built deterministically here from the
`series_level`/`entity` the plan step resolves (itself still the LLM's job -- turning "the
AirWhirl Tower Fan" into `{"sku": "APPL-0004"}` needs a plan/entity-resolution step this
sandbox cannot run without a model; production wires that in, tests pass `entity` directly).
Every generated SQL string still goes through the real validator before execution, exactly
as `postgres_tool` would do on its own (defense in depth, 05_security_and_guardrails.md
principle 2).

`prepare_weekly_history`'s stockout adjustment is INV-PY-02 ported directly (it is a trusted
reference implementation, the same status as regression_tool.py's INV-PY-04/05/06 -- never
generated by the model).
"""
from __future__ import annotations

from typing import Callable, Optional

import numpy as np
import pandas as pd

from app.config import settings as default_settings
